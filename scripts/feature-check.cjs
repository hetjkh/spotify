async function request(url, token, method = 'GET', body) {
  const response = await fetch(API + url, { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(body instanceof FormData ? {} : { 'Content-Type': 'application/json' }) }, body: body === undefined ? undefined : body instanceof FormData ? body : JSON.stringify(body), signal: AbortSignal.timeout(20000) })
  return { status: response.status, data: await response.json() }
}

// Exercise bookmarks with a disposable listener; clean only that listener's records.
const { chromium, expect } = require('@playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const mongoose = require('mongoose')
require('dotenv').config()
const WEB = 'http://localhost:3000', API = 'http://localhost:4000'
const email = `bookmark-check-${Date.now()}@example.invalid`
const checks = [], errors = []
let token
async function request(path) {
  const response = await fetch(API + path, { headers: { Authorization: `Bearer ${token}` } })
  assert.equal(response.ok, true, path)
  return response.json()
}
async function main() {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.goto(WEB + '/signup')
    await page.getByLabel('Name', { exact: true }).fill('Bookmark Check Listener')
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.getByLabel('Password', { exact: true }).fill('BookmarkCheck123!')
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await page.waitForURL('**/dashboard')
    token = await page.evaluate(() => localStorage.getItem('groovy-token'))
    const book = (await request('/books/public')).books.find(item => item.title.startsWith('Alice'))
    assert.ok(book)
    await page.goto(WEB + '/listen/' + book.id)
    await page.locator('.book-chapter-row .track-row').first().click()
    await page.waitForFunction(() => { const audio = document.querySelector('audio'); return audio && !audio.paused && audio.currentTime > 0 })
    await page.locator('.player-sidebar').getByRole('button', { name: 'Pause audiobook', exact: true }).click()
    await page.locator('audio').evaluate(audio => { audio.currentTime = 23 })
    await expect.poll(() => page.getByLabel('Chapter progress', { exact: true }).inputValue()).toBe('23')
    page.once('dialog', dialog => dialog.accept('Memorable passage bookmark check'))
    const saved = page.waitForResponse(response => response.url() === API + '/bookmarks' && response.request().method() === 'POST')
    await page.getByRole('button', { name: 'Bookmark this moment', exact: true }).click()
    const response = await saved
    assert.equal(response.status(), 201)
    const { bookmark } = await response.json()
    assert.equal(bookmark.seconds, 23)
    assert.equal(bookmark.chapterId, String(book.chapters[0]._id))
    await expect(page.locator('#main-content').getByText('Memorable passage bookmark check', { exact: false })).toBeVisible()
    checks.push('Player saves the current chapter at 0:23 with a note; book page updates immediately')

    await page.goto(WEB + '/library')
    const libraryNavigation = page.getByRole('navigation', { name: 'Library sections', exact: true })
    const bookmarksLink = libraryNavigation.getByRole('link', { name: 'Bookmarks', exact: true })
    await expect(bookmarksLink).toHaveAttribute('href', '/bookmarks')
    await bookmarksLink.click()
    await page.waitForURL('**/bookmarks')
    await expect(bookmarksLink).toHaveAttribute('aria-current', 'page')
    const card = page.locator('.bookmark-card').filter({ hasText: 'Memorable passage bookmark check' })
    await expect(card).toHaveCount(1)
    await expect(card).toContainText(book.title)
    await expect(card.locator('.time-pill')).toHaveText('0:23')
    await page.reload()
    await expect(card).toBeVisible()
    checks.push('My Library > Bookmarks opens the saved passage with book, chapter and timestamp; persists after reload')

    await page.getByLabel('Search bookmarks, books, and notes...', { exact: true }).fill('missing-note-check')
    await expect(page.locator('.bookmark-card')).toHaveCount(0)
    await page.getByRole('button', { name: 'Clear collection search', exact: true }).click()
    await card.getByRole('button', { name: /^Edit note/ }).click()
    await page.getByLabel('Your note', { exact: true }).fill('Edited memorable passage')
    await page.getByRole('button', { name: 'Save note', exact: true }).click()
    await page.reload()
    const updated = page.locator('.bookmark-card').filter({ hasText: 'Edited memorable passage' })
    await expect(updated).toBeVisible()
    await updated.getByRole('button', { name: 'Jump to moment', exact: true }).click()
    await page.waitForFunction(() => { const audio = document.querySelector('audio'); return audio && !audio.paused && audio.currentTime >= 23 && audio.currentTime < 28 })
    await page.locator('.player-sidebar').getByRole('button', { name: 'Pause audiobook', exact: true }).click()
    checks.push('Search, note editing with persistence, and actual playback from the bookmarked moment work')

    await page.goto(WEB + '/dashboard')
    await expect(page.locator('.studio-bookmark').filter({ hasText: 'Edited memorable passage' })).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(WEB + '/library')
    await bookmarksLink.click()
    await page.waitForURL('**/bookmarks')
    await expect(updated).toBeVisible()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await fs.mkdir('artifacts', { recursive: true })
    await page.screenshot({ path: 'artifacts/bookmarks-mobile.png' })
    checks.push('Bookmarks appear in Dashboard saved moments and are reachable through My Library on mobile')

    page.once('dialog', dialog => dialog.accept())
    await updated.getByRole('button', { name: /^Delete bookmark/ }).click()
    await expect(page.locator('.bookmark-card')).toHaveCount(0)
    assert.equal((await request('/bookmarks')).bookmarks.some(mark => mark._id === bookmark._id), false)
    await page.reload()
    await expect(page.locator('#main-content h1')).toHaveText('Your bookmarks')
    await expect(page.locator('.bookmark-card')).toHaveCount(0)
    checks.push('Deleting a bookmark removes it from the database and stays deleted after reload')
    assert.deepEqual(errors, [])
    await fs.writeFile('artifacts/bookmark-check.json', JSON.stringify({ checks, errors, passedAt: new Date().toISOString() }, null, 2))
    checks.forEach(check => console.log('PASS ' + check))
  } catch (error) {
    await fs.mkdir('artifacts', { recursive: true })
    await page.screenshot({ path: 'artifacts/bookmark-failure.png' })
    throw error
  } finally {
    await browser.close()
    await mongoose.connect(process.env.MONGODB_URI || process.env.MONGO_URI)
    const User = require('../server/models/User')
    const user = await User.findOne({ email })
    if (user) {
      for (const name of ['Bookmark', 'LibraryItem', 'Progress', 'ListeningDay', 'Notice']) await require('../server/models/' + name).deleteMany({ user: user._id })
      await User.deleteOne({ _id: user._id })
    }
    await mongoose.disconnect()
  }
}
main().catch(error => { console.error(error); process.exit(1) })

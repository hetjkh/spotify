const { test, expect } = require('@playwright/test')

test('audio plays, seeks, changes tracks and keeps playing across navigation', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Listen now', exact: true }).click()
  const audio = page.locator('audio')
  await expect.poll(() => audio.evaluate(element => element.currentTime)).toBeGreaterThan(.1)
  await expect.poll(() => audio.evaluate(element => element.paused)).toBe(false)
  await expect(page.locator('.player-sidebar .now-playing-info h2')).toHaveText('In My Feelings')
  await page.locator('.player-sidebar').getByRole('slider', { name: 'Track progress' }).fill('30')
  await expect.poll(() => audio.evaluate(element => element.currentTime)).toBeGreaterThan(29)
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Albums', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Listen to the whole story.' })).toBeVisible()
  await expect.poll(() => audio.evaluate(element => element.currentTime)).toBeGreaterThan(30)
  await page.locator('.player-sidebar').getByRole('button', { name: 'Next track', exact: true }).click()
  await expect(page.locator('.player-sidebar .now-playing-info h2')).toHaveText('Nightfall')
  await expect.poll(() => audio.evaluate(element => element.currentSrc)).toContain('/audio/nightfall.mp3')
  await page.locator('.player-sidebar').getByRole('button', { name: 'Shuffle', exact: true }).click()
  await expect(page.locator('.player-sidebar').getByRole('button', { name: 'Shuffle', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.player-sidebar').getByRole('button', { name: 'Repeat: off' }).click()
  await expect(page.locator('.player-sidebar').getByRole('button', { name: 'Repeat: all' })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.player-sidebar').getByRole('button', { name: 'Repeat: all' }).click()
  await page.locator('.player-sidebar').getByRole('slider', { name: 'Volume', exact: true }).fill('0.35')
  await expect.poll(() => audio.evaluate(element => element.volume)).toBe(.35)
  await page.locator('.player-sidebar').getByRole('button', { name: 'Mute', exact: true }).click()
  await expect.poll(() => audio.evaluate(element => element.volume)).toBe(0)
  await page.locator('.player-sidebar').getByRole('button', { name: 'Unmute', exact: true }).click()
  await expect.poll(() => audio.evaluate(element => element.volume)).toBe(.35)
  await page.locator('.player-sidebar').getByRole('button', { name: 'Pause music', exact: true }).click()
  await expect.poll(() => audio.evaluate(element => element.paused)).toBe(true)
  expect(errors).toEqual([])
})

test('favorites and custom playlists survive a reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Save featured track', exact: true }).click()
  await page.getByRole('navigation', { name: 'Your library' }).getByRole('link', { name: 'Favorites' }).click()
  await expect(page.locator('main .track-row')).toHaveCount(3)
  await page.reload()
  await expect(page.locator('main .track-row')).toHaveCount(3)
  await page.getByRole('button', { name: 'Create playlist', exact: true }).click()
  await page.getByLabel('Playlist name', { exact: true }).fill('Weekend escape')
  await page.getByRole('dialog').getByRole('button', { name: 'Create playlist', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Weekend escape', exact: true })).toBeVisible()
  await page.locator('.suggested-track').filter({ hasText: 'In My Feelings' }).getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.locator('main .track-row')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Weekend escape', exact: true })).toBeVisible()
  await expect(page.locator('main .track-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Play all', exact: true }).click()
  await expect.poll(() => page.locator('audio').evaluate(element => element.currentTime)).toBeGreaterThan(.1)
})


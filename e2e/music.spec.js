test('all routes render with no broken images or horizontal overflow', async ({ page }) => {
  test.setTimeout(90000)
  const routes = ['/', '/genres', '/genres?genre=Ambient', '/artists', '/artists?artist=nova', '/albums', '/radio', '/?tab=podcasts', '/recent', '/collection/tracks', '/collection/playlists', '/collection/albums', '/collection/artists', '/collection/podcasts', '/collection/episodes', '/playlist/after-hours', '/playlist/session-1', '/local', '/charts', '/search', '/search/Luna/albums', '/search/Luna/podcasts']
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  for (const width of [1440, 1024, 820, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    for (const route of width === 1440 || width === 390 ? routes : ['/', '/collection/tracks', '/albums', '/genres']) {
      await page.goto(route, { waitUntil: 'networkidle' })
      expect(await page.locator('main').innerText(), route).not.toBe('')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px ${route}`).toBe(true)
      const broken = await page.locator('img').evaluateAll(images => images.filter(img => img.complete && img.naturalWidth === 0).map(img => img.src))
      expect(broken, `${width}px ${route}`).toEqual([])
    }
  }
  expect(errors).toEqual([])
})
